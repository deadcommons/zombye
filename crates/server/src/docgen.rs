fn cli_page(repo: &Path, src: &Source, report: &mut Report) -> Result<String, String> {
    let _ = src;
    let mut s = front("Command-line flags", "Every flag of the game client and the server.", 4);
    // The server: its module docs are the manual.
    let server_main = std::fs::read_to_string(repo.join("crates/server/src/main.rs")).map_err(|e| e.to_string())?;
    let server_doc: String = server_main.lines().take_while(|l| l.starts_with("//!")).map(|l| l.trim_start_matches("//!").strip_prefix(' ').unwrap_or(l.trim_start_matches("//!"))).collect::<Vec<_>>().join("\n");
    s.push_str("## `zombye-server`\n\n");
    s.push_str(&prose(server_doc.trim_start_matches("`zombye-server`: headless authoritative server.").trim()));
    s.push_str("\n\n");

    // The client: the flag list in AGENTS.md.
    let agents = std::fs::read_to_string(repo.join("AGENTS.md")).map_err(|e| e.to_string())?;
    let client_line = agents.lines().find(|l| l.starts_with("Client flags: `")).unwrap_or("");
    let client_flags = client_line.trim_start_matches("Client flags: `").split('`').next().unwrap_or("");
    s.push_str("## `zombye` (the game)\n\nEach flag with what it takes. Most are for testing, pictures and recordings; a plain start needs none.\n\n");
    let mut flags: Vec<(String, String)> = Vec::new();
    for part in client_flags.split(" --").map(|p| p.trim().trim_start_matches("--")) {
        if part.is_empty() {
            continue;
        }
        let (flag, arg) = part.split_once(' ').unwrap_or((part, ""));
        flags.push((format!("--{flag}"), arg.to_string()));
    }
    s.push_str("| Flag | Takes |\n|---|---|\n");
    for (f, arg) in &flags {
        let _ = writeln!(s, "| `{f}` | {} |", if arg.is_empty() { String::new() } else { cell(&code(arg)) });
    }
    s.push('\n');

    // What the source reads that no doc names.
    let documented_server: BTreeSet<String> = flag_literals(&server_doc);
    let documented_client: BTreeSet<String> = flags.iter().map(|(f, _)| f.clone()).collect();
    let all_docs = format!("{agents}\n{server_doc}");
    for (krate, documented, name) in [("server", &documented_server, "zombye-server"), ("client", &documented_client, "zombye")] {
        let mut read = BTreeSet::new();
        for f in walk(&repo.join("crates").join(krate).join("src"), "rs") {
            let text = std::fs::read_to_string(&f).unwrap_or_default();
            // Only flags read off the command line: `flag("--x")`, `text("--x")`, `value("--x")` and the like.
            for (i, _) in text.match_indices("(\"--") {
                let before = &text[..i];
                let callee: String = before.chars().rev().take_while(|c| c.is_alphanumeric() || *c == '_').collect::<String>().chars().rev().collect();
                if !matches!(callee.as_str(), "flag" | "text" | "value" | "arg" | "opt" | "has" | "get" | "num" | "parse" | "values" | "list" | "float" | "secs") {
                    continue;
                }
                let rest = &text[i + 2..];
                let flag: String = rest.chars().take_while(|c| *c != '"').collect();
                if flag.len() > 3 && flag[2..].chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-') {
                    read.insert(flag);
                }
            }
        }
        for f in read.difference(documented) {
            if !all_docs.contains(f.as_str()) {
                report.warnings.push(format!("{name} reads {f}, which no doc names (AGENTS.md's client flags, the server's module docs)"));
            }
        }
    }
    Ok(s)
}

fn flag_literals(text: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for (i, _) in text.match_indices("--") {
        let f: String = text[i..].chars().take_while(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == '-').collect();
        if f.len() > 2 {
            out.insert(f);
        }
    }
    out
}

