fn mcp_page(tools: &Value, instructions: &str) -> String {
    let empty = Vec::new();
    let tools = tools.as_array().unwrap_or(&empty);
    let mut s = front("MCP tools", "Every tool the game's MCP server offers, as the server lists them.", 2);
    let _ = writeln!(
        s,
        "{} tools, listed by the server itself (`tools/list`). Read-only tools take no game time and change nothing; \
         debug tools set up tests and do what no player could. Start the server with `--no-debug-tools` to leave those out.\n",
        tools.len()
    );
    s.push_str("## What the server tells your agent\n\nWhen an app connects, the server sends these instructions, which most apps pass on to the model:\n\n");
    s.push_str("```text\n");
    s.push_str(instructions.trim());
    s.push_str("\n```\n\n");

    let group = |t: &Value| -> usize {
        if t["_meta"]["zombye/debug"].as_bool() == Some(true) {
            3
        } else if t["annotations"]["readOnlyHint"].as_bool() == Some(true) {
            0
        } else if t["annotations"]["destructiveHint"].as_bool() == Some(true) {
            2
        } else {
            1
        }
    };
    let titles = ["Looking (read-only)", "Playing", "Saves", "Debug"];
    for (g, title) in titles.iter().enumerate() {
        let in_group: Vec<&Value> = tools.iter().filter(|t| group(t) == g).collect();
        if in_group.is_empty() {
            continue;
        }
        let _ = writeln!(s, "## {title}\n");
        for t in in_group {
            let name = t["name"].as_str().unwrap_or("?");
            let _ = writeln!(s, "### `{name}`\n");
            if let Some(title) = t["title"].as_str() {
                let _ = writeln!(s, "**{}**\n", escape_outside_code(title));
            }
            let _ = writeln!(s, "{}\n", prose(t["description"].as_str().unwrap_or("")));
            let props = t["inputSchema"]["properties"].as_object();
            let required: BTreeSet<&str> = t["inputSchema"]["required"].as_array().map(|r| r.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
            match props {
                Some(p) if !p.is_empty() => {
                    s.push_str("| Argument | Type | What it is |\n|---|---|---|\n");
                    for (arg, def) in p {
                        let mut ty = schema_type(def);
                        if required.contains(arg.as_str()) {
                            ty.push_str(", required");
                        }
                        let mut what = def["description"].as_str().unwrap_or("").to_string();
                        if let Some(e) = def["enum"].as_array() {
                            let opts: Vec<String> = e.iter().map(|v| code(&value_text(v).trim_matches('"').to_string())).collect();
                            what = format!("{what} One of: {}.", opts.join(", ")).trim().to_string();
                        }
                        if let Some(d) = def.get("default") {
                            what = format!("{what} Default {}.", code(&value_text(d))).trim().to_string();
                        }
                        let _ = writeln!(s, "| `{arg}` | {} | {} |", cell(&ty), cell(&prose(&what)));
                    }
                    s.push('\n');
                }
                _ => s.push_str("No arguments.\n\n"),
            }
            if t.get("outputSchema").is_some() {
                s.push_str("Also returns its answer as structured JSON (`structuredContent`, with an `outputSchema`).\n\n");
            }
        }
    }
    s
}

fn schema_type(def: &Value) -> String {
    match &def["type"] {
        Value::String(t) => {
            if t == "array" {
                format!("array of {}", schema_type(&def["items"]))
            } else {
                t.clone()
            }
        }
        Value::Array(a) => a.iter().filter_map(Value::as_str).collect::<Vec<_>>().join(" or "),
        _ => {
            if let Some(any) = def["oneOf"].as_array().or(def["anyOf"].as_array()) {
                any.iter().map(schema_type).collect::<Vec<_>>().join(" or ")
            } else {
                "any".to_string()
            }
        }
    }
}

