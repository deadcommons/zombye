// The source tree: structs and enums with their doc comments.

#[derive(Clone, Debug, Default)]
struct Field {
    name: String,
    ty: String,
    doc: String,
}

#[derive(Clone, Debug, Default)]
struct Item {
    /// The file's stem (`items` for `items.rs`, `mod` folders by their folder).
    module: String,
    name: String,
    doc: String,
    /// A struct's fields, or an enum's variants (`ty` empty, or the variant's payload).
    fields: Vec<Field>,
    is_enum: bool,
}

struct Source {
    items: Vec<Item>,
}

impl Source {
    fn read(repo: &Path) -> Result<Source, String> {
        let mut items = Vec::new();
        // sim first: a name found twice resolves to the simulation's.
        for krate in ["sim", "net", "client", "server", "mods"] {
            let dir = repo.join("crates").join(krate).join("src");
            if !dir.is_dir() {
                return Err(format!("{} not found: run --docs from the repo root, or give --repo DIR", dir.display()));
            }
            for file in walk(&dir, "rs") {
                let Ok(text) = std::fs::read_to_string(&file) else { continue };
                let stem = file.file_stem().and_then(|s| s.to_str()).unwrap_or("");
                let module = if stem == "mod" || stem == "lib" || stem == "main" {
                    file.parent().and_then(|p| p.file_name()).and_then(|s| s.to_str()).unwrap_or(stem).to_string()
                } else {
                    stem.to_string()
                };
                parse_items(&text, &module, &mut items);
            }
        }
        Ok(Source { items })
    }

    /// A struct or enum by `name`, or `module::name`; failing an exact module, the first by name.
    fn find(&self, path: &str) -> Option<&Item> {
        let (module, name) = match path.rsplit_once("::") {
            Some((m, n)) => (m.rsplit("::").next(), n),
            None => (None, path),
        };
        module
            .and_then(|m| self.items.iter().find(|i| i.name == name && i.module == m))
            .or_else(|| self.items.iter().find(|i| i.name == name))
    }
}

/// The structs (with named fields) and enums in one file, with their docs.
fn parse_items(text: &str, module: &str, out: &mut Vec<Item>) {
    let lines: Vec<&str> = text.lines().collect();
    let mut doc: Vec<String> = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        let t = lines[i].trim();
        if let Some(d) = t.strip_prefix("///") {
            doc.push(d.strip_prefix(' ').unwrap_or(d).to_string());
            i += 1;
            continue;
        }
        if t.starts_with("#[") || t.is_empty() && doc.is_empty() {
            i += 1;
            continue;
        }
        let head = t.strip_prefix("pub(crate) ").or_else(|| t.strip_prefix("pub ")).unwrap_or(t);
        let kind = if head.starts_with("struct ") { Some(false) } else if head.starts_with("enum ") { Some(true) } else { None };
        if let Some(is_enum) = kind
            && t.ends_with('{')
        {
            let rest = head.split_once(' ').map_or("", |(_, r)| r);
            let name: String = rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
            let (fields, end) = parse_body(&lines, i + 1, is_enum);
            out.push(Item { module: module.to_string(), name, doc: join_doc(&doc), fields, is_enum });
            doc.clear();
            i = end;
            continue;
        }
        doc.clear();
        i += 1;
    }
}

/// A struct's fields or an enum's variants, from the line after its `{` to the matching `}`; and the line
/// after that.
fn parse_body(lines: &[&str], start: usize, is_enum: bool) -> (Vec<Field>, usize) {
    let mut fields = Vec::new();
    let mut doc: Vec<String> = Vec::new();
    let mut depth = 1i32;
    let mut i = start;
    let mut in_attr = 0i32;
    // A run of fields with one doc comment over the first shares it; a `// Section.` comment over a group
    // stands for the fields under it that have none of their own.
    let mut group_doc = String::new();
    let mut section: Vec<String> = Vec::new();
    let mut section_open = false;
    while i < lines.len() {
        let t = lines[i].trim();
        i += 1;
        if depth == 1 && in_attr == 0 {
            if let Some(d) = t.strip_prefix("///") {
                doc.push(d.strip_prefix(' ').unwrap_or(d).to_string());
                continue;
            }
            if t.starts_with("#[") {
                in_attr = bracket_balance(t);
                continue;
            }
            if let Some(c) = t.strip_prefix("//") {
                if !section_open {
                    section.clear();
                    section_open = true;
                }
                section.push(c.trim().to_string());
                group_doc.clear();
                continue;
            }
            if t.is_empty() {
                group_doc.clear();
                continue;
            }
            section_open = false;
            if t.starts_with('}') {
                return (fields, i);
            }
            let line = t.strip_prefix("pub(crate) ").or_else(|| t.strip_prefix("pub ")).unwrap_or(t);
            let ident: String = line.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
            if !ident.is_empty() {
                let after = &line[ident.len()..];
                if is_enum {
                    let ty = after.trim().trim_end_matches(',').trim().trim_end_matches('{').trim();
                    fields.push(Field { name: ident, ty: ty.to_string(), doc: join_doc(&doc) });
                } else if let Some(ty) = after.strip_prefix(':') {
                    let own = join_doc(&doc);
                    let doc = if !own.is_empty() {
                        group_doc = own.clone();
                        own
                    } else if !group_doc.is_empty() && (group_doc.contains(&format!("`{ident}`")) || group_doc.contains(" / ")) {
                        // A shared comment counts only when it plainly covers this one too: it names
                        // it, or reads "this / that".
                        group_doc.clone()
                    } else {
                        join_doc(&section)
                    };
                    fields.push(Field { name: ident, ty: ty.trim().trim_end_matches(',').trim().to_string(), doc });
                }
            }
            doc.clear();
        } else if in_attr > 0 {
            in_attr += bracket_balance(t);
            continue;
        }
        depth += brace_balance(t);
        if depth <= 0 {
            return (fields, i);
        }
    }
    (fields, i)
}

fn bracket_balance(t: &str) -> i32 {
    t.chars().map(|c| match c {
        '[' => 1,
        ']' => -1,
        _ => 0,
    })
    .sum()
}

/// `{` minus `}` on a line, outside strings and `//` comments.
fn brace_balance(t: &str) -> i32 {
    let mut n = 0;
    let mut in_str = false;
    let mut prev = ' ';
    for c in t.chars() {
        if in_str {
            if c == '"' && prev != '\\' {
                in_str = false;
            }
        } else if c == '"' {
            in_str = true;
        } else if c == '/' && prev == '/' {
            break;
        } else if c == '{' {
            n += 1;
        } else if c == '}' {
            n -= 1;
        }
        prev = c;
    }
    n
}

/// Doc comment lines as text: lines joined, a blank line a paragraph break.
fn join_doc(lines: &[String]) -> String {
    let mut out = String::new();
    for l in lines {
        if l.trim().is_empty() {
            out.push_str("\n\n");
        } else {
            if !out.is_empty() && !out.ends_with('\n') {
                out.push(' ');
            }
            out.push_str(l.trim());
        }
    }
    out.trim().to_string()
}

// ---------------------------------------------------------------------------------------------------------
// Markdown helpers.

fn front(title: &str, description: &str, order: u32) -> String {
    format!(
        "---\ntitle: {}\ndescription: {}\neditUrl: false\nsidebar:\n  order: {order}\n---\n\n{MARKER}\n\n",
        yaml(title),
        yaml(description)
    )
}

fn yaml(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Prose from the source made fit for the page: rustdoc links as plain code, issue numbers dropped,
/// `<` outside code escaped (Markdown would read `Vec<T>` as a tag).
fn prose(s: &str) -> String {
    let mut s = s.replace("[`", "`").replace("`]", "`");
    // " (#12)", "(#73, " and the like: the tracker's numbers mean nothing to a reader of the site.
    loop {
        let Some(at) = find_issue(&s) else { break };
        let (start, end) = at;
        s.replace_range(start..end, "");
    }
    s = s.replace("()", "").replace("( ", "(").replace(" )", ")").replace(" ,", ",");
    escape_outside_code(&s)
}

/// The span of one issue reference to drop: ` (#N)`, `#N, ` or `, #N`.
fn find_issue(s: &str) -> Option<(usize, usize)> {
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'#' && i + 1 < b.len() && b[i + 1].is_ascii_digit() && (i == 0 || !b[i - 1].is_ascii_alphanumeric()) {
            let mut j = i + 1;
            while j < b.len() && b[j].is_ascii_digit() {
                j += 1;
            }
            // " (#N)"
            if i >= 2 && b[i - 1] == b'(' && b[i - 2] == b' ' && j < b.len() && b[j] == b')' {
                return Some((i - 2, j + 1));
            }
            if i >= 1 && b[i - 1] == b'(' && j < b.len() && b[j] == b')' {
                return Some((i - 1, j + 1));
            }
            // "#N, " inside a list
            if j + 1 < b.len() && b[j] == b',' && b[j + 1] == b' ' {
                return Some((i, j + 2));
            }
            // ", #N"
            if i >= 2 && b[i - 1] == b' ' && b[i - 2] == b',' {
                return Some((i - 2, j));
            }
            // "; #N"
            if i >= 2 && b[i - 1] == b' ' && b[i - 2] == b';' {
                return Some((i - 2, j));
            }
            i = j;
            continue;
        }
        i += 1;
    }
    None
}

fn escape_outside_code(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut code = false;
    for c in s.chars() {
        if c == '`' {
            code = !code;
        }
        match c {
            '<' if !code => out.push_str("&lt;"),
            '>' if !code => out.push_str("&gt;"),
            _ => out.push(c),
        }
    }
    out
}

/// One table cell: one line, pipes escaped.
fn cell(s: &str) -> String {
    s.replace("\n\n", " ").replace('\n', " ").replace('|', "\\|")
}

fn code(s: &str) -> String {
    if s.contains('`') { format!("`` {s} ``") } else { format!("`{s}`") }
}

/// A value as a RON reader would write it, short.
fn value_text(v: &Value) -> String {
    match v {
        Value::Null => "none".to_string(),
        Value::Bool(b) => b.to_string(),
        Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                i.to_string()
            } else if let Some(f) = n.as_f64() {
                // Tunings are f32: show the shortest text that is that f32, not its f64 widening.
                let f32v = f as f32;
                if f32v.is_finite() && (f32v as f64 - f).abs() <= f.abs() * 1e-6 { format!("{f32v}") } else { format!("{f}") }
            } else {
                n.to_string()
            }
        }
        Value::String(s) => format!("\"{s}\""),
        Value::Array(a) => format!("[{}]", a.iter().map(value_text).collect::<Vec<_>>().join(", ")),
        Value::Object(o) => {
            // An enum variant with data comes out as {"Variant": ...}.
            if o.len() == 1 {
                let (k, v) = o.iter().next().unwrap();
                if k.chars().next().is_some_and(char::is_uppercase) {
                    return match v {
                        Value::Array(a) => format!("{k}({})", a.iter().map(value_text).collect::<Vec<_>>().join(", ")),
                        Value::Object(_) => format!("{k}{}", value_text(v)),
                        _ => format!("{k}({})", value_text(v)),
                    };
                }
            }
            format!("({})", o.iter().map(|(k, v)| format!("{k}: {}", value_text(v))).collect::<Vec<_>>().join(", "))
        }
    }
}

/// A short value for a table cell; a long one is cut.
fn short_value(v: &Value, max: usize) -> String {
    let t = value_text(v);
    if t.chars().count() <= max { t } else { format!("{}…", t.chars().take(max).collect::<String>()) }
}

