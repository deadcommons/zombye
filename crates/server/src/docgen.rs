fn tuning_page(src: &Source, config: &zombye_sim::WorldConfig, report: &mut Report) -> String {
    let mut s = front("Tuning", "Every gameplay number that isn't in a data file, with its value as the game ships.", 3);
    s.push_str(
        "Every number the simulation plays by that a data file doesn't hold. Values are as shipped, after the data files \
         are read (a block a data file fills, such as fire, shows the file's values). A world keeps the settings it was \
         made with in its save, and the difficulty presets scale some of them.\n\n",
    );
    let Some(world) = src.find("world::WorldConfig") else {
        report.warnings.push("WorldConfig not found in crates/sim/src/world.rs".to_string());
        return s;
    };
    let values = tuning_values(config);
    for f in &world.fields {
        if NOT_TUNING.contains(&f.name.as_str()) {
            continue;
        }
        let Some((_, value)) = values.iter().find(|(n, _)| *n == f.name) else {
            report.warnings.push(format!("WorldConfig::{} is neither on the tuning page nor marked as content (docgen.rs: tuning_values, NOT_TUNING)", f.name));
            continue;
        };
        let _ = writeln!(s, "## `{}`\n", f.name);
        if f.doc.is_empty() {
            report.warnings.push(format!("WorldConfig::{} has no doc comment", f.name));
        } else {
            let _ = writeln!(s, "{}\n", prose(&f.doc));
        }
        let ty = base_type(&f.ty);
        match src.find(&ty).filter(|i| !i.is_enum) {
            Some(item) if value.is_object() => struct_values(&mut s, src, item, value, &f.name, 3, report),
            _ => {
                let _ = writeln!(s, "Value: {}\n", code(&value_text(value)));
            }
        }
    }
    s
}

/// A struct's fields with their values: a table, and a sub-section for each field that is a struct itself.
fn struct_values(s: &mut String, src: &Source, item: &Item, value: &Value, path: &str, level: usize, report: &mut Report) {
    if !item.doc.is_empty() && level > 3 {
        let _ = writeln!(s, "{}\n", prose(&item.doc));
    }
    let mut nested = Vec::new();
    let mut rows = String::new();
    for f in &item.fields {
        let Some(v) = value.get(&f.name) else { continue };
        let sub = src.find(&base_type(&f.ty)).filter(|i| !i.is_enum && !i.fields.is_empty());
        if let Some(sub) = sub
            && v.is_object()
            && level < 5
        {
            nested.push((f, sub, v));
            continue;
        }
        if f.doc.is_empty() {
            report.warnings.push(format!("{}::{} ({path}.{}) has no doc comment", item.name, f.name, f.name));
        }
        let _ = writeln!(rows, "| `{}` | {} | {} |", f.name, cell(&code(&short_value(v, 60))), cell(&prose(&f.doc)));
    }
    if !rows.is_empty() {
        s.push_str("| Field | Shipped | What it does |\n|---|---|---|\n");
        s.push_str(&rows);
        s.push('\n');
    }
    for (f, sub, v) in nested {
        let _ = writeln!(s, "{} `{path}.{}`\n", "#".repeat(level), f.name);
        if !f.doc.is_empty() {
            let _ = writeln!(s, "{}\n", prose(&f.doc));
        }
        struct_values(s, src, sub, v, &format!("{path}.{}", f.name), level + 1, report);
    }
}

/// `Option<crate::fire::FireTuning>` → `fire::FireTuning`; `Vec<T>` → `T`.
fn base_type(ty: &str) -> String {
    let mut t = ty.trim();
    loop {
        let mut changed = false;
        for wrap in ["Option<", "Vec<", "Box<", "std::sync::Arc<", "Arc<"] {
            if let Some(inner) = t.strip_prefix(wrap).and_then(|r| r.strip_suffix('>')) {
                t = inner.trim();
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }
    let t = t.trim_start_matches("crate::").trim_start_matches("zombye_sim::");
    t.to_string()
}

