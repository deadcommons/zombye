//! `zombye-server --docs DIR`: the game's reference, written as Markdown pages from the game itself, so the
//! docs site never drifts from what ships.
//!
//! Four sources, none of them typed out by hand:
//! - every MCP tool as `tools/list` gives it (name, title, annotations, description, arguments) and the
//!   instructions the server sends an agent on connecting;
//! - every data file under the data folder: its header comment, the schema it is read as (the Rust
//!   structs, their fields and doc comments, read from the source tree), the values it ships, and the
//!   file itself;
//! - every tuning block of `WorldConfig` with its value as shipped (after the data files are applied)
//!   and the doc comment of each field;
//! - the command-line flags, from the server's module docs and the client's flag list in AGENTS.md,
//!   checked against the flags the source actually reads.
//!
//! It also says what isn't documented: a data file missing from [`DATA_FILES`], a file with no header
//! comment, a schema or tuning field with no doc comment, a flag the source reads that no doc names.
//! `--docs-strict` makes any of those an error (exit 1), for CI.
//!
//! Generated pages carry [`MARKER`]; a run removes the generated pages it no longer writes (a data file
//! taken out), and leaves every other file in DIR alone.

