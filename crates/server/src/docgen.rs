/// What a run found undocumented.
#[derive(Default)]
pub struct Report {
    pub pages: usize,
    pub warnings: Vec<String>,
}

/// Write every page into `out`. `repo` is the source tree's root (for the doc comments and flag lists),
/// `data` the data folder, `config` the world config as loaded from it, `tools` the MCP `tools/list`
/// array and `instructions` what the server tells an agent on connecting.
/// `base` is the site path the pages are served under (links between them are absolute: the docs site
/// refuses relative ones).
pub fn write(out: &Path, base: &str, repo: &Path, data: &Path, config: &zombye_sim::WorldConfig, tools: &Value, instructions: &str) -> Result<Report, String> {
    let src = Source::read(repo)?;
    let mut report = Report::default();
    let mut pages: BTreeMap<PathBuf, String> = BTreeMap::new();
    let commit = std::env::var("ZOMBYE_DOCS_COMMIT").ok().filter(|c| !c.trim().is_empty());

    pages.insert("mcp-tools.md".into(), mcp_page(tools, instructions));
    pages.insert("tuning.md".into(), tuning_page(&src, config, &mut report));
    pages.insert("cli.md".into(), cli_page(repo, &src, &mut report)?);
    let files = data_pages(&src, data, config, &mut report, &mut pages)?;
    pages.insert("index.md".into(), index_page(base.trim_end_matches('/'), &files, tools, commit.as_deref()));

    std::fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    // Our pages from an earlier run that this one doesn't write again (a data file taken out) go.
    for old in walk(out, "md") {
        let rel = old.strip_prefix(out).unwrap_or(&old).to_path_buf();
        if !pages.contains_key(&rel) && std::fs::read_to_string(&old).is_ok_and(|t| t.contains(MARKER)) {
            let _ = std::fs::remove_file(&old);
        }
    }
    for (rel, text) in &pages {
        let path = out.join(rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    report.pages = pages.len();
    Ok(report)
}

