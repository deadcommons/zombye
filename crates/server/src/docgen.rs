struct DataPage {
    slug: String,
    file: String,
    part: Part,
    summary: &'static str,
}

fn data_pages(src: &Source, data: &Path, config: &zombye_sim::WorldConfig, report: &mut Report, pages: &mut BTreeMap<PathBuf, String>) -> Result<Vec<DataPage>, String> {
    let mut out = Vec::new();
    let shipped: BTreeSet<String> = walk(data, "ron").iter().filter_map(|p| p.strip_prefix(data).ok()).map(|p| p.to_string_lossy().replace('\\', "/")).collect();
    for f in &shipped {
        let known = DATA_FILES.iter().any(|(path, ..)| if path.ends_with('/') { f.starts_with(path) } else { f == path });
        if !known {
            report.warnings.push(format!("data file {f} has no entry in DATA_FILES (crates/server/src/docgen.rs): it isn't documented"));
        }
    }
    for (order, (path, schema, part, summary)) in DATA_FILES.iter().enumerate() {
        let folder = path.ends_with('/');
        let files: Vec<&String> = shipped.iter().filter(|f| if folder { f.starts_with(path) } else { f == path }).collect();
        if files.is_empty() {
            report.warnings.push(format!("DATA_FILES lists {path}, which the data folder doesn't have"));
            continue;
        }
        let slug = path.trim_end_matches('/').rsplit('/').next().unwrap_or(path).trim_end_matches(".ron").replace('_', "-");
        let title = if folder { format!("{}*.ron", path) } else { path.to_string() };
        let mut s = front(&title, summary, 10 + order as u32);
        let _ = writeln!(s, "**{summary}** {}\n", match part {
            Part::Rules => "Read by the game's rules: a change here changes how the game plays, and a world remembers the content it was made with.",
            Part::Look => "Read by the game client only: a change here changes how it looks or sounds, never how it plays.",
        });
        let _ = writeln!(s, "File: `assets/data/{path}`{}\n", if folder { format!(" ({} files)", files.len()) } else { String::new() });

        // The header comment of the (first) file, as its author wrote it.
        let first = data.join(files[0]);
        let text = std::fs::read_to_string(&first).map_err(|e| format!("{}: {e}", first.display()))?;
        let header = header_comment(&text);
        if header.is_empty() {
            report.warnings.push(format!("{} has no header comment saying what it is", files[0]));
        } else {
            s.push_str("## About this file\n\n");
            s.push_str(&header_markdown(&header));
            s.push('\n');
        }

        // The schema.
        let list = schema.starts_with('[');
        let name = schema.trim_start_matches('[').trim_end_matches(']');
        match src.find(name) {
            Some(item) => {
                s.push_str("## Fields\n\n");
                if list {
                    let _ = writeln!(s, "The file is a list of `{}`, each in round brackets.\n", item.name);
                } else {
                    let _ = writeln!(s, "The file is one `{}`.\n", item.name);
                }
                let mut seen = BTreeSet::new();
                let mut notes = FieldNotes::default();
                for f in &files {
                    notes.read(&std::fs::read_to_string(data.join(f)).unwrap_or_default());
                }
                schema_tables(&mut s, src, item, 3, &mut seen, &notes.done(), report);
            }
            None => report.warnings.push(format!("{path}: schema {name} not found in the source")),
        }

        // What ships, for the lists people look things up in.
        if let Some(table) = shipped_table(path, config) {
            s.push_str("## As shipped\n\n");
            s.push_str(&table);
            s.push('\n');
        }

        if folder {
            s.push_str("## The files\n\n");
            for f in &files {
                let body = std::fs::read_to_string(data.join(f)).unwrap_or_default();
                let _ = writeln!(s, "<details>\n<summary><code>{f}</code></summary>\n\n```ron\n{}\n```\n\n</details>\n", body.trim_end());
            }
        } else {
            let _ = writeln!(s, "## The file\n\n<details>\n<summary>The whole file as shipped</summary>\n\n```ron\n{}\n```\n\n</details>", text.trim_end());
        }
        pages.insert(PathBuf::from("data").join(format!("{slug}.md")), s);
        out.push(DataPage { slug, file: title, part: *part, summary });
    }
    Ok(out)
}

/// The leading `//` lines of a file, without the slashes.
fn header_comment(text: &str) -> Vec<String> {
    text.lines()
        .take_while(|l| l.trim_start().starts_with("//"))
        .map(|l| {
            let l = l.trim_start().trim_start_matches("//");
            l.strip_prefix(' ').unwrap_or(l).to_string()
        })
        .collect()
}

/// A header comment as Markdown: lines joined into paragraphs, and runs of indented lines (a little table
/// in the comment) kept as they are.
fn header_markdown(lines: &[String]) -> String {
    let mut out = String::new();
    let mut prose_run: Vec<&str> = Vec::new();
    let mut laid_out: Vec<&str> = Vec::new();
    let flush = |out: &mut String, prose_run: &mut Vec<&str>, laid_out: &mut Vec<&str>| {
        if !prose_run.is_empty() {
            let _ = writeln!(out, "{}\n", prose(&prose_run.join(" ")));
            prose_run.clear();
        }
        if !laid_out.is_empty() {
            let _ = writeln!(out, "```text\n{}\n```\n", laid_out.join("\n"));
            laid_out.clear();
        }
    };
    for l in lines {
        if l.trim().is_empty() {
            flush(&mut out, &mut prose_run, &mut laid_out);
        } else if l.starts_with("  ") {
            if !prose_run.is_empty() {
                let _ = writeln!(out, "{}\n", prose(&prose_run.join(" ")));
                prose_run.clear();
            }
            laid_out.push(l);
        } else {
            if !laid_out.is_empty() {
                let _ = writeln!(out, "```text\n{}\n```\n", laid_out.join("\n"));
                laid_out.clear();
            }
            prose_run.push(l);
        }
    }
    flush(&mut out, &mut prose_run, &mut laid_out);
    out
}

/// A table of a struct's fields, then one for each struct or enum a field names (each once).
fn schema_tables(s: &mut String, src: &Source, item: &Item, level: usize, seen: &mut BTreeSet<String>, notes: &BTreeMap<String, String>, report: &mut Report) {
    seen.insert(item.name.clone());
    if !item.doc.is_empty() {
        let _ = writeln!(s, "{}\n", prose(&item.doc));
    }
    let mut more = Vec::new();
    if item.is_enum {
        s.push_str("| Value | What it means |\n|---|---|\n");
        for v in &item.fields {
            let name = if v.ty.is_empty() { v.name.clone() } else { format!("{}{}", v.name, v.ty) };
            let _ = writeln!(s, "| {} | {} |", cell(&code(&name)), cell(&prose(&v.doc)));
        }
        s.push('\n');
    } else {
        s.push_str("| Field | Type | What it is |\n|---|---|---|\n");
        for f in &item.fields {
            // The Rust doc comment, else the comment the data file has over that field.
            let doc = if f.doc.is_empty() { notes.get(&f.name).cloned().unwrap_or_default() } else { f.doc.clone() };
            if doc.is_empty() {
                report.warnings.push(format!("{}::{} has no doc comment, in the source or the data file", item.name, f.name));
            }
            let _ = writeln!(s, "| `{}` | {} | {} |", f.name, cell(&code(&f.ty)), cell(&prose(&doc)));
            for name in type_names(&f.ty) {
                if let Some(sub) = src.find(&name)
                    && !seen.contains(&sub.name)
                    && !sub.fields.is_empty()
                {
                    seen.insert(sub.name.clone());
                    more.push(sub);
                }
            }
        }
        s.push('\n');
    }
    for sub in more {
        if level > 6 {
            break;
        }
        let _ = writeln!(s, "{} `{}`\n", "#".repeat(level.min(6)), sub.name);
        schema_tables(s, src, sub, level + 1, seen, notes, report);
    }
}

/// The comments a data file has right over its fields (`// ...` lines, then `name: ...`), by field name. A
/// name commented differently in two places is dropped: which comment is meant can't be told.
#[derive(Default)]
struct FieldNotes {
    notes: BTreeMap<String, Option<String>>,
}

impl FieldNotes {
    fn read(&mut self, text: &str) {
        let mut comment: Vec<String> = Vec::new();
        let mut header = true;
        for line in text.lines() {
            let t = line.trim();
            if let Some(c) = t.strip_prefix("//") {
                if !header {
                    comment.push(c.trim().to_string());
                }
                continue;
            }
            header = false;
            let ident: String = t.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
            let is_field = !ident.is_empty() && t[ident.len()..].trim_start().starts_with(':') && !t[ident.len()..].trim_start().starts_with("::");
            if is_field && !comment.is_empty() {
                let note = join_doc(&comment);
                match self.notes.get(&ident) {
                    None => {
                        self.notes.insert(ident, Some(note));
                    }
                    Some(Some(old)) if *old != note => {
                        self.notes.insert(ident, None);
                    }
                    _ => {}
                }
            }
            comment.clear();
        }
    }

    fn done(self) -> BTreeMap<String, String> {
        self.notes.into_iter().filter_map(|(k, v)| v.map(|v| (k, v))).collect()
    }
}

/// The type names inside a field's type (`Option<Vec<(String, u32)>>` → `String`, ...).
fn type_names(ty: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut word = String::new();
    for c in ty.chars().chain(std::iter::once(' ')) {
        if c.is_alphanumeric() || c == '_' || c == ':' {
            word.push(c);
        } else {
            if word.chars().last().is_some_and(char::is_alphanumeric) {
                let name = word.rsplit("::").next().unwrap_or(&word).to_string();
                if name.chars().next().is_some_and(char::is_uppercase) && !matches!(name.as_str(), "Option" | "Vec" | "String" | "Box" | "BTreeMap" | "HashMap" | "Arc") {
                    out.push(name);
                }
            }
            word.clear();
        }
    }
    out
}

/// A table of what ships, for the files people look things up in.
fn shipped_table(path: &str, c: &zombye_sim::WorldConfig) -> Option<String> {
    let rows: Vec<Value> = match path {
        "items/items.ron" => c.items.iter().filter_map(|i| serde_json::to_value(i).ok()).collect(),
        "items/weapons.ron" => c.weapons.iter().filter_map(|w| serde_json::to_value(w).ok()).collect(),
        "items/recipes.ron" => c.recipes.iter().filter_map(|r| serde_json::to_value(r).ok()).collect(),
        "build.ron" => c.builds.iter().filter_map(|b| serde_json::to_value(b).ok()).collect(),
        _ => return None,
    };
    if rows.is_empty() {
        return None;
    }
    // The columns: fields short enough to read in a cell in most rows.
    let mut cols: Vec<String> = Vec::new();
    if let Some(Value::Object(first)) = rows.first() {
        for k in first.keys() {
            let shown = rows.iter().filter(|r| r.get(k).is_some_and(|v| !v.is_null() && value_text(v).chars().count() <= 40)).count();
            if shown * 2 >= rows.len() && cols.len() < 12 {
                cols.push(k.clone());
            }
        }
    }
    // The id and name first.
    for k in ["name", "id"] {
        if let Some(at) = cols.iter().position(|c| c == k) {
            let c = cols.remove(at);
            cols.insert(0, c);
        }
    }
    let mut s = String::new();
    let _ = writeln!(s, "{} entries. Columns are the fields short enough for a table; the rest are in the file below.\n", rows.len());
    let _ = writeln!(s, "| {} |", cols.iter().map(|c| format!("`{c}`")).collect::<Vec<_>>().join(" | "));
    let _ = writeln!(s, "|{}", "---|".repeat(cols.len()));
    for r in &rows {
        let cells: Vec<String> = cols.iter().map(|c| r.get(c).map_or(String::new(), |v| if v.is_null() { String::new() } else { cell(&escape_outside_code(&short_value(v, 40))) })).collect();
        let _ = writeln!(s, "| {} |", cells.join(" | "));
    }
    Some(s)
}

