        assert_eq!(items.len(), 2);
        let t = &items[0];
        assert_eq!((t.name.as_str(), t.doc.as_str(), t.is_enum), ("Thing", "A thing.", false));
        let names: Vec<_> = t.fields.iter().map(|f| (f.name.as_str(), f.ty.as_str(), f.doc.as_str())).collect();
